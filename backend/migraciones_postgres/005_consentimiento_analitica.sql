-- Registro del consentimiento para las ESTADISTICAS DE USO (banner de privacidad).
--
-- Principio de minimizacion: solo se guarda lo necesario para poder demostrar la decision.
--  * aceptado : lleva el identificador anonimo de estadisticas (sesion_id), que existe SOLO
--               porque la persona acepto. Los eventos de evento_analitica solo se reciben
--               si su sesion_id tiene una fila 'aceptado' de la version vigente.
--  * rechazado: NO lleva ningun identificador (no se genera ni se guarda nada del visitante).
--  * retirado : al retirar el consentimiento se borra el sesion_id de la fila (queda solo la
--               decision, su fecha y la fecha de retiro) y se borran sus eventos.

CREATE TABLE consentimientos_privacidad (
    CONSTRAINT pk_consentimientos_privacidad PRIMARY KEY (id),
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    finalidad varchar(20) NOT NULL DEFAULT 'analitica',
    decision varchar(10) NOT NULL,
    version varchar(20) NOT NULL,
    sesion_id varchar(64),
    decidido_en timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    retirado_en timestamp,
    CONSTRAINT uq_consentimientos_sesion_id UNIQUE (sesion_id),
    CONSTRAINT chk_consentimientos_finalidad CHECK (finalidad IN ('analitica')),
    CONSTRAINT chk_consentimientos_decision CHECK (decision IN ('aceptado', 'rechazado', 'retirado')),
    CONSTRAINT chk_consentimientos_sesion CHECK ((decision = 'aceptado') = (sesion_id IS NOT NULL)),
    CONSTRAINT chk_consentimientos_retiro CHECK ((decision = 'retirado') = (retirado_en IS NOT NULL))
);
CREATE INDEX idx_consentimientos_decidido ON consentimientos_privacidad (decidido_en);
