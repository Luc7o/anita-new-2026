-- Esquema base de Anita New Style en PostgreSQL (Neon).
-- Generado a partir del esquema final de MySQL (migraciones 000 a 066) y revisado a mano.
-- Cambios de motor: boolean en vez de tinyint(1), jsonb, timestamp en UTC, identidad en vez de
-- AUTO_INCREMENT, texto sin distinguir mayusculas (citext) donde MySQL lo hacia por la colacion.

CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS unaccent;

CREATE TABLE categorias (
    CONSTRAINT pk_categorias PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre citext NOT NULL,
    slug citext NOT NULL,
    descripcion varchar(300),
    icono varchar(100) DEFAULT 'bag',
    activo boolean NOT NULL DEFAULT true,
    imagen_url varchar(500),
    CONSTRAINT uq_categorias_nombre UNIQUE (nombre),
    CONSTRAINT uq_categorias_slug UNIQUE (slug)
);

CREATE TABLE colores (
    CONSTRAINT pk_colores PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre citext NOT NULL,
    codigo_hex varchar(7),
    CONSTRAINT uq_colores_nombre UNIQUE (nombre)
);

CREATE TABLE configuracion_tienda (
    CONSTRAINT pk_configuracion_tienda PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre_comercial varchar(120) NOT NULL,
    logo_url varchar(400),
    correo_contacto varchar(120),
    telefono varchar(20),
    whatsapp varchar(20),
    direccion varchar(200),
    referencia varchar(200),
    ciudad varchar(80),
    horario_atencion varchar(120),
    maps_url varchar(400),
    facebook_url varchar(200),
    instagram_url varchar(200),
    tiktok_url varchar(200),
    moneda varchar(3) NOT NULL,
    actualizado_en timestamp
);

CREATE TABLE latencia_requests (
    CONSTRAINT pk_latencia_requests PRIMARY KEY (id),
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    endpoint varchar(150) NOT NULL,
    metodo varchar(10) NOT NULL,
    latencia_ms integer NOT NULL,
    status_code smallint NOT NULL,
    fecha_creacion timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE INDEX idx_endpoint ON latencia_requests (endpoint);
CREATE INDEX idx_latencia_fecha ON latencia_requests (fecha_creacion);

CREATE TABLE proveedores (
    CONSTRAINT pk_proveedores PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre varchar(150) NOT NULL,
    contacto_nombre varchar(120),
    telefono varchar(20),
    email varchar(120),
    direccion varchar(200),
    ruc varchar(20),
    notas text,
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT uq_proveedores_ruc UNIQUE (ruc)
);

CREATE TABLE roles (
    CONSTRAINT pk_roles PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo varchar(20) NOT NULL,
    nombre varchar(50) NOT NULL,
    CONSTRAINT uq_roles_codigo UNIQUE (codigo)
);

CREATE TABLE tallas (
    CONSTRAINT pk_tallas PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre citext NOT NULL,
    orden integer DEFAULT 0,
    CONSTRAINT uq_tallas_nombre UNIQUE (nombre)
);

CREATE TABLE ubigeo_departamentos (
    CONSTRAINT pk_ubigeo_departamentos PRIMARY KEY (id),
    id integer NOT NULL,
    nombre varchar(50) NOT NULL,
    codigo char(2) NOT NULL,
    CONSTRAINT uq_ubigeo_departamentos_codigo UNIQUE (codigo)
);

CREATE TABLE productos (
    CONSTRAINT pk_productos PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre varchar(150) NOT NULL,
    descripcion text,
    precio numeric(10,2) NOT NULL,
    precio_oferta numeric(10,2),
    stock integer DEFAULT 0,
    sku citext,
    categoria_id integer NOT NULL,
    destacado boolean NOT NULL DEFAULT false,
    es_nuevo boolean NOT NULL DEFAULT true,
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    fecha_actualizacion timestamp,
    genero varchar(20),
    costo_promedio numeric(10,2),
    stock_minimo integer NOT NULL DEFAULT 3,
    CONSTRAINT uq_productos_sku UNIQUE (sku),
    CONSTRAINT fk_productos_categoria_id FOREIGN KEY (categoria_id) REFERENCES categorias (id),
    CONSTRAINT chk_productos_genero CHECK ((genero is null) or (genero in ('mujer','hombre','unisex','nina','nino'))),
    CONSTRAINT chk_productos_oferta CHECK ((precio_oferta is null) or (precio_oferta < precio)),
    CONSTRAINT chk_productos_precio CHECK ((precio >= 0) and ((precio_oferta is null) or (precio_oferta >= 0))),
    CONSTRAINT chk_productos_stock CHECK (stock >= 0),
    CONSTRAINT chk_productos_stock_minimo CHECK (stock_minimo >= 0)
);
CREATE INDEX idx_productos_categoria_id ON productos (categoria_id);

CREATE TABLE ubigeo_provincias (
    CONSTRAINT pk_ubigeo_provincias PRIMARY KEY (id),
    id integer NOT NULL,
    nombre varchar(100) NOT NULL,
    codigo char(4) NOT NULL,
    departamento_id integer NOT NULL,
    CONSTRAINT uq_ubigeo_provincias_codigo UNIQUE (codigo),
    CONSTRAINT fk_provincias_departamento FOREIGN KEY (departamento_id) REFERENCES ubigeo_departamentos (id)
);
CREATE INDEX idx_provincias_departamento ON ubigeo_provincias (departamento_id);

CREATE TABLE imagenes_producto (
    CONSTRAINT pk_imagenes_producto PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    producto_id integer NOT NULL,
    url varchar(400) NOT NULL,
    orden integer DEFAULT 0,
    fecha_creacion timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    color_id integer,
    CONSTRAINT fk_imagenes_color FOREIGN KEY (color_id) REFERENCES colores (id),
    CONSTRAINT fk_imagenes_producto_producto_id FOREIGN KEY (producto_id) REFERENCES productos (id) ON DELETE CASCADE
);
CREATE INDEX idx_imagenes_color ON imagenes_producto (color_id);
CREATE INDEX idx_imagenes_producto_producto_id ON imagenes_producto (producto_id);

CREATE TABLE promociones (
    CONSTRAINT pk_promociones PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    etiqueta varchar(60) DEFAULT '',
    titulo varchar(150) NOT NULL,
    descripcion varchar(400) DEFAULT '',
    imagen_url varchar(400) DEFAULT '',
    boton_texto varchar(60) DEFAULT 'Ver Todo',
    boton_link varchar(200) DEFAULT '/tienda',
    fecha_inicio date,
    fecha_fin date,
    activo boolean NOT NULL DEFAULT true,
    orden integer DEFAULT 0,
    fecha_creacion timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    fecha_actualizacion timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    producto_id integer,
    CONSTRAINT fk_promociones_producto FOREIGN KEY (producto_id) REFERENCES productos (id) ON DELETE SET NULL,
    CONSTRAINT chk_promociones_fechas CHECK ((fecha_inicio is null) or (fecha_fin is null) or (fecha_fin >= fecha_inicio))
);
CREATE INDEX idx_promociones_producto_id ON promociones (producto_id);

CREATE TABLE proveedor_productos (
    CONSTRAINT pk_proveedor_productos PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    proveedor_id integer NOT NULL,
    producto_id integer NOT NULL,
    precio_compra numeric(10,2),
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT uq_proveedor_producto UNIQUE (proveedor_id, producto_id),
    CONSTRAINT fk_pp_producto FOREIGN KEY (producto_id) REFERENCES productos (id) ON DELETE CASCADE,
    CONSTRAINT fk_pp_proveedor FOREIGN KEY (proveedor_id) REFERENCES proveedores (id) ON DELETE CASCADE
);
CREATE INDEX idx_proveedor_productos_producto_id ON proveedor_productos (producto_id);

CREATE TABLE ubigeo_distritos (
    CONSTRAINT pk_ubigeo_distritos PRIMARY KEY (id),
    id integer NOT NULL,
    nombre varchar(150) NOT NULL,
    codigo char(6) NOT NULL,
    provincia_id integer NOT NULL,
    CONSTRAINT uq_ubigeo_distritos_codigo UNIQUE (codigo),
    CONSTRAINT fk_distritos_provincia FOREIGN KEY (provincia_id) REFERENCES ubigeo_provincias (id)
);
CREATE INDEX idx_distritos_provincia ON ubigeo_distritos (provincia_id);

CREATE TABLE variantes_producto (
    CONSTRAINT pk_variantes_producto PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    producto_id integer NOT NULL,
    stock integer NOT NULL DEFAULT 0,
    talla_id integer NOT NULL,
    color_id integer NOT NULL,
    CONSTRAINT uq_variante_id_producto UNIQUE (id, producto_id),
    CONSTRAINT uq_variante_producto UNIQUE (producto_id, talla_id, color_id),
    CONSTRAINT fk_variantes_color FOREIGN KEY (color_id) REFERENCES colores (id),
    CONSTRAINT fk_variantes_talla FOREIGN KEY (talla_id) REFERENCES tallas (id),
    CONSTRAINT fk_variantes_producto_producto_id FOREIGN KEY (producto_id) REFERENCES productos (id) ON DELETE CASCADE,
    CONSTRAINT chk_variantes_stock CHECK (stock >= 0)
);
CREATE INDEX idx_variantes_color ON variantes_producto (color_id);
CREATE INDEX idx_variantes_talla ON variantes_producto (talla_id);

