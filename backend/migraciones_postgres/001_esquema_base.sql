CREATE TABLE carrito (
    CONSTRAINT pk_carrito PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id integer NOT NULL,
    producto_id integer NOT NULL,
    cantidad integer NOT NULL DEFAULT 1,
    fecha_creacion timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    variante_id integer,
    CONSTRAINT fk_carrito_usuario_id FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_carrito_producto_id FOREIGN KEY (producto_id) REFERENCES productos (id) ON DELETE CASCADE,
    CONSTRAINT fk_carrito_variante FOREIGN KEY (variante_id, producto_id) REFERENCES variantes_producto (id, producto_id) ON DELETE CASCADE,
    CONSTRAINT chk_carrito_cantidad CHECK (cantidad > 0)
);
CREATE INDEX idx_carrito_variante_id_producto_id ON carrito (variante_id, producto_id);
CREATE INDEX idx_carrito_producto_id ON carrito (producto_id);

CREATE TABLE codigos_respaldo (
    CONSTRAINT pk_codigos_respaldo PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id integer NOT NULL,
    codigo_hash varchar(64) NOT NULL,
    usado_en timestamp,
    fecha_creacion timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT uq_codigos_respaldo_usuario_hash UNIQUE (usuario_id, codigo_hash),
    CONSTRAINT fk_codigos_respaldo_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT chk_codigos_respaldo_hash CHECK (char_length(codigo_hash) = 64)
);

CREATE TABLE compras (
    CONSTRAINT pk_compras PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    proveedor_id integer NOT NULL,
    tipo_documento varchar(20),
    numero_documento varchar(40),
    fecha_compra date NOT NULL,
    estado varchar(30) NOT NULL DEFAULT 'recibida',
    total numeric(12,2) NOT NULL DEFAULT 0.00,
    notas text,
    usuario_id integer,
    anulada_por integer,
    fecha_anulacion timestamp,
    motivo_anulacion varchar(255),
    fecha_creacion timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT fk_compras_anulada_por FOREIGN KEY (anulada_por) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT fk_compras_proveedor FOREIGN KEY (proveedor_id) REFERENCES proveedores (id),
    CONSTRAINT fk_compras_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_compras_estado CHECK (estado IN ('recibida', 'anulada')),
    CONSTRAINT chk_compras_total CHECK (total >= 0)
);
CREATE INDEX idx_compras_anulada_por ON compras (anulada_por);
CREATE INDEX idx_compras_usuario_id ON compras (usuario_id);
CREATE INDEX idx_compras_fecha ON compras (fecha_compra);

