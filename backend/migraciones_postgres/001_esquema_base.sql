CREATE TABLE pedidos (
    CONSTRAINT pk_pedidos PRIMARY KEY (id),
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    numero_pedido varchar(30) NOT NULL,
    idempotency_key varchar(64),
    usuario_id integer,
    estado varchar(20) DEFAULT 'pendiente',
    estado_pago varchar(20) DEFAULT 'pendiente',
    metodo_pago varchar(20) NOT NULL,
    tipo_entrega varchar(20) DEFAULT 'delivery',
    subtotal numeric(10,2) NOT NULL,
    costo_envio numeric(10,2) DEFAULT 0.00,
    total numeric(10,2) NOT NULL,
    envio_nombre varchar(160),
    envio_telefono varchar(20),
    envio_direccion varchar(200),
    envio_distrito varchar(100),
    envio_provincia varchar(100),
    envio_dpto varchar(100),
    envio_referencia varchar(200),
    nota text,
    fecha_creacion timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    culqi_cargo_id varchar(40),
    origen varchar(20) NOT NULL DEFAULT 'online',
    pago_idempotency_key varchar(64),
    fecha_limite_pago timestamp,
    fecha_pago timestamp,
    fecha_entregado timestamp,
    motivo_cancelacion varchar(50),
    distrito_id integer,
    envio_tipo_documento varchar(10),
    envio_numero_documento varchar(15),
    envio_email varchar(120),
    codigo_recojo char(6),
    CONSTRAINT uq_pedidos_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT uq_pedidos_numero_pedido UNIQUE (numero_pedido),
    CONSTRAINT uq_pedidos_culqi_cargo_id UNIQUE (culqi_cargo_id),
    CONSTRAINT fk_pedidos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_pedidos_distrito_id FOREIGN KEY (distrito_id) REFERENCES ubigeo_distritos (id),
    CONSTRAINT chk_pedidos_estado CHECK (estado in ('pendiente','confirmado','preparando','listo_recojo','enviado','entregado','cancelado')),
    CONSTRAINT chk_pedidos_estado_pago CHECK (estado_pago in ('pendiente','en_revision','verificado','rechazado','no_aplica','reembolso_pendiente','reembolsado')),
    CONSTRAINT chk_pedidos_importes CHECK ((subtotal >= 0) and (total >= 0) and ((costo_envio is null) or (costo_envio >= 0))),
    CONSTRAINT chk_pedidos_metodo_pago CHECK (metodo_pago in ('yape','tarjeta','efectivo')),
    CONSTRAINT chk_pedidos_origen CHECK (origen in ('online','presencial')),
    CONSTRAINT chk_pedidos_tipo_entrega CHECK (tipo_entrega in ('delivery','recojo'))
);
CREATE INDEX idx_pedidos_distrito_id ON pedidos (distrito_id);
CREATE INDEX idx_pedidos_estado ON pedidos (estado, estado_pago);
CREATE INDEX idx_pedidos_fecha_creacion ON pedidos (fecha_creacion);
CREATE INDEX idx_pedidos_usuario_id ON pedidos (usuario_id);

